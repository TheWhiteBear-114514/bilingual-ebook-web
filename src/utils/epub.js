/**
 * 端上生成真实的 EPUB（零依赖 ZIP/EPUB 写入器）。
 * 后端就绪后由服务端生成，这里用于 Mock 模式，保证「下载的文件能真正打开」。
 */
import { LANG_NAME } from '@/utils/constants'

const CRC_TABLE = (() => {
  const t = new Uint32Array(256)
  for (let n = 0; n < 256; n++) {
    let c = n
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1
    t[n] = c >>> 0
  }
  return t
})()

function crc32(bytes) {
  let c = 0xffffffff
  for (let i = 0; i < bytes.length; i++) c = CRC_TABLE[(c ^ bytes[i]) & 0xff] ^ (c >>> 8)
  return (c ^ 0xffffffff) >>> 0
}

function buildZip(files) {
  const enc = new TextEncoder()
  const chunks = []
  const central = []
  let offset = 0
  const now = new Date()
  const dosTime = (now.getHours() << 11) | (now.getMinutes() << 5) | (now.getSeconds() >> 1)
  const dosDate = ((now.getFullYear() - 1980) << 9) | ((now.getMonth() + 1) << 5) | now.getDate()

  for (const f of files) {
    const nameB = enc.encode(f.name)
    const crc = crc32(f.data)
    const dl = f.data.length
    const lh = new DataView(new ArrayBuffer(30))
    lh.setUint32(0, 0x04034b50, true)
    lh.setUint16(4, 20, true)
    lh.setUint16(6, 0x0800, true)
    lh.setUint16(8, 0, true)
    lh.setUint16(10, dosTime, true)
    lh.setUint16(12, dosDate, true)
    lh.setUint32(14, crc, true)
    lh.setUint32(18, dl, true)
    lh.setUint32(22, dl, true)
    lh.setUint16(26, nameB.length, true)
    lh.setUint16(28, 0, true)
    chunks.push(new Uint8Array(lh.buffer), nameB, f.data)

    const ch = new DataView(new ArrayBuffer(46))
    ch.setUint32(0, 0x02014b50, true)
    ch.setUint16(4, 20, true)
    ch.setUint16(6, 20, true)
    ch.setUint16(8, 0x0800, true)
    ch.setUint16(10, 0, true)
    ch.setUint16(12, dosTime, true)
    ch.setUint16(14, dosDate, true)
    ch.setUint32(16, crc, true)
    ch.setUint32(20, dl, true)
    ch.setUint32(24, dl, true)
    ch.setUint16(28, nameB.length, true)
    ch.setUint32(42, offset, true)
    central.push(new Uint8Array(ch.buffer), nameB)
    offset += 30 + nameB.length + dl
  }

  const cdSize = central.reduce((s, c) => s + c.length, 0)
  const eo = new DataView(new ArrayBuffer(22))
  eo.setUint32(0, 0x06054b50, true)
  eo.setUint16(8, files.length, true)
  eo.setUint16(10, files.length, true)
  eo.setUint32(12, cdSize, true)
  eo.setUint32(16, offset, true)
  return new Blob([...chunks, ...central, new Uint8Array(eo.buffer)], { type: 'application/epub+zip' })
}

const esc = (s = '') =>
  String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')

export function buildEpub(book) {
  const enc = new TextEncoder()
  const segs = book.segments || book.segs || []
  const ch1 =
    '<?xml version="1.0" encoding="utf-8"?>' +
    '<html xmlns="http://www.w3.org/1999/xhtml" lang="zh"><head><title>' +
    esc(book.title) +
    '</title><style>body{font-family:"Noto Serif CJK SC","Songti SC",serif;line-height:1.85}' +
    'h1{font-size:1.3em;text-align:center}h2{font-size:1.05em;text-align:center;color:#555;font-weight:400}' +
    '.s{margin:.5em 0 0}.t{margin:0 0 1.2em;color:#1e40af;background:#eff6ff;padding:.35em .6em;' +
    'border-left:3px solid #93c5fd;border-radius:0 .3em .3em 0}' +
    '.f{color:#92400e;background:#fffbeb;border-left:3px solid #fcd34d}' +
    '.note{font-size:.8em;color:#888;text-align:center;margin-top:2em}</style></head><body>' +
    '<h1>' + esc(book.title) + '</h1><h2>双语对照版（' +
    esc(LANG_NAME[book.source_lang] || book.source_lang) + ' → ' +
    esc(LANG_NAME[book.target_lang] || book.target_lang) + '）</h2>' +
    segs
      .map(
        (s) =>
          '<p class="s">' + esc(s.source_text) + '</p>' +
          (s.is_failed
            ? '<p class="t f">⚠ 翻译失败，保留原文</p>'
            : '<p class="t">' + esc(s.translated_text) + '</p>')
      )
      .join('') +
    '<p class="note">Generated by Bilingual E-Book Studio</p></body></html>'

  const opf =
    '<?xml version="1.0" encoding="utf-8"?>' +
    '<package xmlns="http://www.idpf.org/2007/opf" version="3.0" unique-identifier="uid">' +
    '<metadata xmlns:dc="http://purl.org/dc/elements/1.1/">' +
    '<dc:identifier id="uid">bes-' + book.id + '</dc:identifier>' +
    '<dc:title>' + esc(book.title) + ' 双语对照版</dc:title><dc:language>zh</dc:language>' +
    '<meta property="dcterms:modified">' +
    new Date().toISOString().replace(/\.\d+Z$/, 'Z') +
    '</meta></metadata>' +
    '<manifest><item id="ch1" href="ch1.xhtml" media-type="application/xhtml+xml"/>' +
    '<item id="nav" href="nav.xhtml" media-type="application/xhtml+xml" properties="nav"/></manifest>' +
    '<spine><itemref idref="ch1"/></spine></package>'

  const nav =
    '<?xml version="1.0" encoding="utf-8"?>' +
    '<html xmlns="http://www.w3.org/1999/xhtml" xmlns:epub="http://www.idpf.org/2007/ops">' +
    '<head><title>目录</title></head><body><nav epub:type="toc"><ol>' +
    '<li><a href="ch1.xhtml">全文 · 双语对照</a></li></ol></nav></body></html>'

  const container =
    '<?xml version="1.0"?>' +
    '<container version="1.0" xmlns="urn:oasis:names:tc:opendocument:xmlns:container">' +
    '<rootfiles><rootfile full-path="OEBPS/content.opf" ' +
    'media-type="application/oebps-package+xml"/></rootfiles></container>'

  return buildZip([
    { name: 'mimetype', data: enc.encode('application/epub+zip') },
    { name: 'META-INF/container.xml', data: enc.encode(container) },
    { name: 'OEBPS/content.opf', data: enc.encode(opf) },
    { name: 'OEBPS/nav.xhtml', data: enc.encode(nav) },
    { name: 'OEBPS/ch1.xhtml', data: enc.encode(ch1) }
  ])
}

export function downloadBlob(blob, filename) {
  const url = URL.createObjectURL(blob)
  const a = document.createElement('a')
  a.href = url
  a.download = filename
  document.body.appendChild(a)
  a.click()
  setTimeout(() => {
    URL.revokeObjectURL(url)
    a.remove()
  }, 1500)
}
